import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { randomUUID } from "node:crypto";

const directory = process.env.CRUNCHIFY_BACKUP_DIR || join(process.env.LOCALAPPDATA, "Crunchify", "Backups");
const credential = join(directory, "backup-credential.dpapi");
const helper = resolve("scripts/backup-dpapi.ps1");
const pgDump = process.env.CRUNCHIFY_PG_DUMP || "C:/Program Files/PostgreSQL/18/bin/pg_dump.exe";
const pgRestore = process.env.CRUNCHIFY_PG_RESTORE || "C:/Program Files/PostgreSQL/18/bin/pg_restore.exe";
const maxBytes = 64 * 1024 * 1024;
if (!existsSync(credential)) throw new Error("Backup credential is not configured for this Windows user");
mkdirSync(directory, { recursive: true });
const decrypted = spawnSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-File", helper, "-Mode", "Unprotect", "-Path", credential], { maxBuffer: 1024 * 1024 });
if (decrypted.status !== 0) throw new Error("Could not unlock the backup credential for this Windows user");
let url;
try { url = new URL(decrypted.stdout.toString("utf8")); } catch { throw new Error("Invalid backup connection target"); }
decrypted.stdout.fill(0);
const localTest = process.env.CRUNCHIFY_BACKUP_TEST_MODE === "1" && ["127.0.0.1", "localhost", "[::1]"].includes(url.hostname);
if (!localTest && (!["postgres:", "postgresql:"].includes(url.protocol) || url.pathname !== "/postgres" || url.hostname !== "aws-0-ap-southeast-1.pooler.supabase.com" || url.port !== "5432" || url.username !== "crunchify_backup_app.wnrotadxjouvnklueprl" || url.searchParams.get("sslmode") !== "verify-full")) throw new Error("Unexpected backup connection target");
const certSource = readFileSync(resolve("src/server/db/connection.ts"), "utf8");
const ca = certSource.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/)?.[0];
if (!ca) throw new Error("Supabase CA certificate is missing");
const caPath = join(directory, "supabase-root-2021.pem");
writeFileSync(caPath, `${ca}\n`);
const env = { ...process.env, PGHOST: url.hostname, PGPORT: url.port || "5432", PGUSER: decodeURIComponent(url.username), PGPASSWORD: decodeURIComponent(url.password), PGDATABASE: decodeURIComponent(url.pathname.slice(1)), PGSSLMODE: localTest ? "disable" : "verify-full", PGSSLROOTCERT: caPath };
const dump = spawnSync(pgDump, ["--format=custom", "--schema=crunchify_private", "--no-owner", "--no-acl"], { env, maxBuffer: maxBytes, timeout: 120000 });
delete env.PGPASSWORD;
if (dump.status !== 0 || dump.error) throw new Error("Database export failed or exceeded the 64 MiB safety limit");
const stamp = new Date().toISOString().replace(/[:.]/g, "-");
const encrypted = join(directory, `crunchify-${stamp}-${randomUUID()}.dpapi.tmp`);
const protectedDump = spawnSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-File", helper, "-Mode", "Protect", "-Path", encrypted], { input: dump.stdout, maxBuffer: 1024 * 1024, timeout: 120000 });
dump.stdout.fill(0);
if (protectedDump.status !== 0) throw new Error("Could not encrypt the backup");
const restored = spawnSync("powershell.exe", ["-NoProfile", "-NonInteractive", "-File", helper, "-Mode", "Unprotect", "-Path", encrypted], { maxBuffer: maxBytes, timeout: 120000 });
if (restored.status !== 0 || restored.error) throw new Error("Could not decrypt the backup for verification");
const listing = spawnSync(pgRestore, ["--list"], { input: restored.stdout, maxBuffer: 4 * 1024 * 1024, timeout: 120000 });
restored.stdout.fill(0);
if (listing.status !== 0 || !listing.stdout.toString("utf8").includes("TABLE DATA crunchify_private inquiries")) throw new Error("Backup archive verification failed");
const finalPath = encrypted.slice(0, -4);
renameSync(encrypted, finalPath);
console.log(`Encrypted database backup created and archive listing verified: ${finalPath}`);
